<?php

declare(strict_types=1);

namespace GoCardlessSDK\DTOs;

/**
 * Redirect Flows
 *
 * <p class="deprecated-notice"><strong>Deprecated</strong>: Redirect Flows are legacy APIs and cannot be used by new integrators.
 *     The <a href="https://docs.gocardless.com/docs/api-reference/billing-request">Billing Request flow</a> API should be used for your payment flows.</p>
 *
 * Redirect flows enable you to use GoCardless' [hosted payment pages](https://pay-sandbox.gocardless.com/AL000000AKFPFF) to set up mandates with your customers. These pages are fully compliant and have been translated into Danish, Dutch, French, German, Italian, Norwegian, Portuguese, Slovak, Spanish and Swedish.
 *
 * The overall flow is:
 *
 * 1. You [create](https://docs.gocardless.com/docs/api-reference/redirect-flow#create-a-redirect-flow) a redirect flow for your customer, and redirect them to the returned redirect url, e.g. `https://pay.gocardless.com/flow/RE123`.
 *
 * 2. Your customer supplies their name, email, address, and bank account details, and submits the form. This securely stores their details, and redirects them back to your `success_redirect_url` with `redirect_flow_id=RE123` in the querystring.
 *
 * 3. You [complete](https://docs.gocardless.com/docs/api-reference/redirect-flow#complete-a-redirect-flow) the redirect flow, which creates a [customer](https://docs.gocardless.com/docs/api-reference/customer), [customer bank account](https://docs.gocardless.com/docs/api-reference/customer-bank-account), and [mandate](https://docs.gocardless.com/docs/api-reference/mandate), and returns the ID of the mandate. You may wish to create a [subscription](https://docs.gocardless.com/docs/api-reference/subscription) or [payment](https://docs.gocardless.com/docs/api-reference/payment) at this point.
 *
 * Once you have [completed](https://docs.gocardless.com/docs/api-reference/redirect-flow#complete-a-redirect-flow) the redirect flow via the API, you should display a confirmation page to your customer, confirming that their Direct Debit has been set up. You can build your own page, or redirect to the one we provide in the `confirmation_url` attribute of the redirect flow.
 *
 * Redirect flows expire 30 minutes after they are first created. You cannot complete an expired redirect flow. For an integrator this is shorter and they will expire after 10 minutes.
 */
final class RedirectFlow extends \Dmorenof\SdkRuntime\DTO
{
    protected const string ADDITIONAL_PROPERTIES_TYPE = 'mixed';
    protected const bool ADDITIONAL_PROPERTIES_NULLABLE = false;

    /**
     * The URL of a confirmation page, which you may optionally redirect the customer to rather than use your own page, that confirms in their chosen language that their Direct Debit has been set up successfully. Only returned once the customer has set up their mandate via the payment pages and the redirect flow has been [completed](https://docs.gocardless.com/docs/api-reference/redirect-flow#complete-a-redirect-flow), and only available for 15 minutes from when you complete the redirect flow. The structure of this URL may change at any time, so you should read it directly from the API response.
     */
    public string $confirmation_url;
    /**
     * Fixed [timestamp](https://docs.gocardless.com/docs/api-reference/data-conventions#dates-and-times), recording when this resource was created.
     * Format: date-time
     */
    public string $created_at;
    /**
     * A description of the item the customer is paying for. This will be shown on the hosted payment pages.
     */
    public ?string $description;
    /**
     * Unique identifier, beginning with "RE".
     */
    public string $id;
    public \GoCardlessSDK\DTOs\RedirectFlow\Links $links;
    /**
     * Mandate reference generated by GoCardless or submitted by an integrator.
     */
    public string $mandate_reference;
    public \GoCardlessSDK\DTOs\RedirectFlow\Metadata $metadata;
    /**
     * The URL of the hosted payment pages for this redirect flow. This is the URL you should redirect your customer to.
     */
    public string $redirect_url;
    public \GoCardlessSDK\Enums\RedirectFlow\Scheme $scheme;
    /**
     * The customer's session ID must be provided when the redirect flow is set up and again when it is completed. This allows integrators to ensure that the user who was originally sent to the GoCardless payment pages is the one who has completed them.
     */
    public string $session_token;
    /**
     * The URL to redirect to upon successful mandate setup. You must use a URL beginning `https` in the live environment.
     */
    public string $success_redirect_url;

    protected function assignMember(string $name, mixed $value): void
    {
        match ($name) {
            'confirmation_url' => is_string($value) ? $this->confirmation_url = $value : parent::assignMember($name, $value),
            'created_at' => is_string($value) ? $this->created_at = $value : parent::assignMember($name, $value),
            'description' => $value === null || is_string($value) ? $this->description = $value : parent::assignMember($name, $value),
            'id' => is_string($value) ? $this->id = $value : parent::assignMember($name, $value),
            'links' => $value instanceof \stdClass ? $this->links = new \GoCardlessSDK\DTOs\RedirectFlow\Links($value) : parent::assignMember($name, $value),
            'mandate_reference' => is_string($value) ? $this->mandate_reference = $value : parent::assignMember($name, $value),
            'redirect_url' => is_string($value) ? $this->redirect_url = $value : parent::assignMember($name, $value),
            'scheme' => is_string($value) ? $this->scheme = \GoCardlessSDK\Enums\RedirectFlow\Scheme::from($value) : parent::assignMember($name, $value),
            'session_token' => is_string($value) ? $this->session_token = $value : parent::assignMember($name, $value),
            'success_redirect_url' => is_string($value) ? $this->success_redirect_url = $value : parent::assignMember($name, $value),
            default => parent::assignMember($name, $value),
        };
    }
}
